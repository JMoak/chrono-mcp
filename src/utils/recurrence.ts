/**
 * Recurrence expansion: RFC 5545 RRULE and ISO 8601 repeating intervals.
 *
 * This module turns a recurrence expression into concrete occurrence
 * instants, feeding the TIME_CALCULATOR `expand` operation. Two grammars are
 * accepted:
 *
 * - **RFC 5545 RRULE** — the recurrence format stored internally by Google
 *   Calendar, Outlook, and Apple Calendar. Expansion is delegated to
 *   `rrule-temporal`, which performs the calendar math on the Temporal API
 *   and therefore preserves wall-clock times across DST transitions
 *   (validated against a DST battery; the classic `rrule` package returns
 *   zone-less "fake UTC" instants and was rejected).
 *
 * - **ISO 8601 repeating intervals** — `R[n]/<start>/<duration>`, e.g.
 *   `R5/2026-03-01T14:00:00Z/P1D`. Occurrences are generated by successive
 *   calendar-aware addition in the start instant's zone, so
 *   `R12/2026-01-05T09:00:00[America/New_York]/P1W` stays 09:00 New York
 *   wall-clock across DST. The start instant accepts RFC 9557 (IXDTF)
 *   annotations via {@link parseInstant}. `R` with no count repeats without
 *   bound; `Rn` produces n occurrences (the start plus n-1 repetitions).
 *
 * Expansion is always bounded: an occurrence cap is mandatory and window
 * bounds are honored, with explicit truncation reporting — never a silent
 * cut. Unbounded rules without a window end are capped and flagged.
 *
 * @module recurrence
 */

import { DateTime, Duration } from "luxon";
import { RRuleTemporal } from "rrule-temporal";
import { parseInstant } from "./ixdtf.js";

/** Result of a successful recurrence expansion. */
export interface ExpandResult {
	/** Which grammar the recurrence string was recognized as */
	ruleType: "rrule" | "iso8601_repeating_interval";
	/** Occurrence instants, chronologically ordered, zone-aware */
	occurrences: DateTime[];
	/** True when more occurrences exist beyond the cap or scan bound */
	truncated: boolean;
}

/** Discriminated result: expansion data or a human-readable error. */
export type ExpandOutcome =
	| { success: true; data: ExpandResult }
	| { success: false; error: string };

/** Options controlling recurrence expansion. */
export interface ExpandOptions {
	/** RRULE string (with or without DTSTART/RRULE: prefixes) or ISO 8601 repeating interval */
	recurrence: string;
	/** DTSTART fallback when an RRULE string carries none */
	dtstart?: DateTime | undefined;
	/** Inclusive lower bound; earlier occurrences are skipped */
	windowStart?: DateTime | undefined;
	/** Inclusive upper bound; expansion stops beyond it */
	windowEnd?: DateTime | undefined;
	/** Hard cap on returned occurrences */
	maxOccurrences: number;
}

/** Matches the ISO 8601 repeating-interval prefix: R or Rn followed by '/'. */
const ISO_REPEAT_RE = /^R(\d*)\//i;

/** Iteration guard for interval scanning (window skipping, tiny durations). */
const MAX_SCAN_ITERATIONS = 100_000;

/**
 * Expands a recurrence expression into concrete occurrences.
 *
 * @param options - Recurrence string, optional DTSTART, window, and cap
 * @returns Occurrences with truncation metadata, or an error description
 */
export function expandRecurrence(options: ExpandOptions): ExpandOutcome {
	const trimmed = options.recurrence.trim();
	if (ISO_REPEAT_RE.test(trimmed)) {
		return expandRepeatingInterval(trimmed, options);
	}
	return expandRRule(trimmed, options);
}

/**
 * Expands an ISO 8601 repeating interval (`R[n]/<start>/<duration>`).
 *
 * The start/duration split is taken at the last `/P` so that IXDTF zone
 * annotations containing `/` (e.g. `[America/New_York]`) parse correctly.
 */
function expandRepeatingInterval(
	recurrence: string,
	options: ExpandOptions,
): ExpandOutcome {
	const prefixMatch = recurrence.match(ISO_REPEAT_RE);
	const countStr = prefixMatch?.[1] ?? "";
	const count = countStr === "" ? Number.POSITIVE_INFINITY : Number(countStr);
	if (count === 0) {
		return { success: true, data: emptyResult("iso8601_repeating_interval") };
	}

	const body = recurrence.slice((prefixMatch?.[0] ?? "").length);
	const durationSlash = body.lastIndexOf("/P");
	if (durationSlash === -1) {
		return {
			success: false,
			error: `Repeating interval must be R[n]/<start>/<duration>, got: ${recurrence}`,
		};
	}
	const startStr = body.slice(0, durationSlash);
	const durationStr = body.slice(durationSlash + 1);

	let start = parseInstant(startStr);
	if (start.isValid && !startStr.includes("[")) {
		// The interval start's own offset/Z is authoritative for rendering;
		// never let the server's host zone leak into occurrence output.
		const preserved = DateTime.fromISO(startStr, { setZone: true });
		if (preserved.isValid) start = preserved;
	}
	if (!start.isValid) {
		return {
			success: false,
			error: `Invalid repeating interval start "${startStr}": ${start.invalidReason}`,
		};
	}
	const duration = Duration.fromISO(durationStr);
	if (!duration.isValid) {
		return {
			success: false,
			error: `Invalid repeating interval duration "${durationStr}"`,
		};
	}
	if (duration.toMillis() <= 0) {
		return {
			success: false,
			error: `Repeating interval duration must be positive, got "${durationStr}"`,
		};
	}

	const occurrences: DateTime[] = [];
	let truncated = false;
	let current = start;
	let produced = 0;
	let iterations = 0;

	while (produced < count) {
		if (++iterations > MAX_SCAN_ITERATIONS) {
			return {
				success: false,
				error: `Expansion exceeded ${MAX_SCAN_ITERATIONS} iterations before reaching the window; narrow the window or enlarge the interval`,
			};
		}
		if (options.windowEnd && current > options.windowEnd) {
			break;
		}
		if (!options.windowStart || current >= options.windowStart) {
			if (occurrences.length >= options.maxOccurrences) {
				truncated = true;
				break;
			}
			occurrences.push(current);
		}
		produced++;
		current = current.plus(duration);
	}

	return {
		success: true,
		data: { ruleType: "iso8601_repeating_interval", occurrences, truncated },
	};
}

/**
 * Expands an RFC 5545 RRULE via rrule-temporal.
 *
 * Accepts a full iCalendar snippet (DTSTART + RRULE lines), a lone
 * `RRULE:...` line, or a bare `FREQ=...` rule part; when no DTSTART is
 * present the `dtstart` option supplies it.
 */
function expandRRule(recurrence: string, options: ExpandOptions): ExpandOutcome {
	let ruleString = recurrence;
	if (!/^DTSTART/im.test(ruleString)) {
		const dtstart = options.dtstart;
		if (!dtstart?.isValid) {
			return {
				success: false,
				error:
					"RRULE has no DTSTART; provide base_time to anchor the recurrence",
			};
		}
		const ruleLine = /^RRULE:/im.test(ruleString)
			? ruleString
			: `RRULE:${ruleString}`;
		ruleString = `${composeDtstart(dtstart)}\n${ruleLine}`;
	} else if (!/^RRULE:/im.test(ruleString)) {
		return {
			success: false,
			error: `Recurrence contains DTSTART but no RRULE line: ${recurrence}`,
		};
	}

	let rule: RRuleTemporal;
	try {
		rule = new RRuleTemporal({ rruleString: ruleString });
	} catch (error) {
		return {
			success: false,
			error: `Invalid RRULE "${recurrence}": ${error instanceof Error ? error.message : String(error)}`,
		};
	}

	const max = options.maxOccurrences;
	let zonedOccurrences: { epochMilliseconds: number; timeZoneId: string }[];
	try {
		if (options.windowEnd) {
			// Bounded scan: iterate up to the window end, then filter/cap below.
			zonedOccurrences = rule.between(
				options.windowStart?.toJSDate() ?? new Date(-8640000000000000),
				options.windowEnd.toJSDate(),
				true,
			);
		} else {
			// No upper bound: take one past the cap to detect truncation.
			zonedOccurrences = rule.all((_, i) => i <= max);
			if (options.windowStart) {
				const startMs = options.windowStart.toMillis();
				zonedOccurrences = zonedOccurrences.filter(
					(z) => z.epochMilliseconds >= startMs,
				);
			}
		}
	} catch (error) {
		return {
			success: false,
			error: `RRULE expansion failed: ${error instanceof Error ? error.message : String(error)}`,
		};
	}

	const truncated = zonedOccurrences.length > max;
	const occurrences = zonedOccurrences
		.slice(0, max)
		.map((z) => DateTime.fromMillis(z.epochMilliseconds, { zone: z.timeZoneId }));

	return { success: true, data: { ruleType: "rrule", occurrences, truncated } };
}

/**
 * Composes an iCalendar DTSTART line from a DateTime: TZID form for IANA
 * zones, UTC form otherwise (fixed-offset zones are normalized to UTC).
 */
function composeDtstart(dt: DateTime): string {
	const zone = dt.zoneName ?? "";
	if (dt.zone.isUniversal && zone !== "UTC") {
		// Fixed offset (e.g. UTC+5:30) is not a valid TZID; anchor in UTC.
		return `DTSTART:${dt.toUTC().toFormat("yyyyLLdd'T'HHmmss")}Z`;
	}
	const tzid = zone === "UTC" ? "Etc/UTC" : zone;
	return `DTSTART;TZID=${tzid}:${dt.toFormat("yyyyLLdd'T'HHmmss")}`;
}

/** Empty successful expansion for a given rule type. */
function emptyResult(ruleType: ExpandResult["ruleType"]): ExpandResult {
	return { ruleType, occurrences: [], truncated: false };
}
